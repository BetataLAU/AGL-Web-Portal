// ===== HKIA CDP：Local Mock Server（模擬 CTO 環境）=====
// 目的：未取得 AAHK 憑證前也能完整跑 Full Flow / Lite Flow（含 202 + 延遲 Callback）。
// 回應形狀刻意對齊 Spec，讓前端與程式碼片段可以直接沿用。
const { getMockState, saveMockState } = require('./store');

function nextSeq(state) {
  state.counter = (Number(state.counter) || 0) + 1;
  return state.counter;
}

function scenarioOf(body, scenario) {
  const raw = String(scenario || (body && body.mockScenario) || 'success').toLowerCase();
  const allowed = ['success', 'cto_reject', 'validation_error', 'not_found', 'timeout', 'rate_limit'];
  return allowed.includes(raw) ? raw : 'success';
}

function errorResponse(status, code, message, extra) {
  return {
    status,
    body: Object.assign({ error: message, code, timestamp: new Date().toISOString() }, extra || {})
  };
}

async function sampleRclPdfBase64(ref, ctoCode) {
  try {
    const { PDFDocument, StandardFonts, rgb } = require('pdf-lib');
    const doc = await PDFDocument.create();
    const page = doc.addPage([595.28, 841.89]); // A4
    const bold = await doc.embedFont(StandardFonts.HelveticaBold);
    const font = await doc.embedFont(StandardFonts.Helvetica);
    page.drawText('HKIA CDP - Reference Control List (MOCK)', { x: 48, y: 790, size: 14, font: bold, color: rgb(0.1, 0.2, 0.5) });
    page.drawText(`RA Reference: ${ref || '-'}`, { x: 48, y: 762, size: 10, font });
    page.drawText(`CTO: ${ctoCode || 'AAT'}`, { x: 48, y: 746, size: 10, font });
    page.drawText('This PDF is generated by the local mock server.', { x: 48, y: 718, size: 10, font });
    page.drawText('MAWB            DEST   PCS    WEIGHT(KG)', { x: 48, y: 686, size: 10, font: bold });
    page.drawText('160-1234 5678   HKG     10      950.5', { x: 48, y: 670, size: 10, font });
    page.drawText('160-8765 4321   HKG      4      420.0', { x: 48, y: 654, size: 10, font });
    const bytes = await doc.save();
    return Buffer.from(bytes).toString('base64');
  } catch (err) {
    return '';
  }
}

const nowIso = () => new Date().toISOString();

async function handleMock(options) {
  const opts = options || {};
  const api = opts.api;
  const params = Object.assign({}, opts.params || {}, opts.query || {});
  const body = (opts.body && typeof opts.body === 'object') ? opts.body : {};
  const scenario = scenarioOf(body, opts.scenario);
  const requestId = opts.requestId || '';
  const state = getMockState();
  const ctoCode = String(body.ctoCode || params.ctoCode || 'AAT').toUpperCase();

  if (scenario === 'rate_limit') return errorResponse(429, 'CDP_070', 'Too Many Requests（mock：15 req/sec）');
  if (scenario === 'timeout') return errorResponse(504, 'GLS_010', 'Gateway Timeout（mock：30 秒）');
  if (scenario === 'validation_error') {
    return errorResponse(422, 'CDP_011', 'Validation failed（mock scenario）', {
      cto_errors: [{ code: '108717', field: 'weight', message: 'Weight allows 1 decimal place only' }]
    });
  }
  if (scenario === 'not_found') return errorResponse(404, 'CDP_030', 'Resource not found（mock scenario）');

  const finish = (payload) => {
    saveMockState(state);
    return payload;
  };

  switch (api) {
    case '#401': {
      const seq = nextSeq(state);
      const ref = `RA-${ctoCode}-${String(seq).padStart(6, '0')}`;
      const ctoRef = `CTO${ctoCode}${String(seq).padStart(6, '0')}`;
      const rejected = scenario === 'cto_reject';
      const status = rejected ? 'REJECTED_FROM_CTO' : 'ACCEPTED_FROM_CTO';
      state.preDeclarations[ref] = {
        ra_reference_id: ref,
        cto_predeclaration_num: ctoRef,
        ctoCode,
        mawbNumber: body.mawbNumber || body.mawb || '',
        cargoType: body.cargoType || '',
        status,
        documentId: body.documentId || '',
        requestId,
        createdAt: nowIso(),
        payload: body
      };
      return finish({
        status: rejected ? 200 : 202,
        body: {
          ra_reference_id: ref,
          status: 'ACCEPTED',
          message: 'Request accepted for processing（async）',
          x_request_id: requestId
        },
        callback: {
          source_id: requestId,
          event: rejected ? 'pre-declaration.rejected' : 'pre-declaration.accepted',
          status,
          api,
          ra_reference_id: ref,
          cto_predeclaration_num: ctoRef,
          ctoCode,
          cto_errors: rejected ? [{ code: '108717', field: 'weight', message: 'Weight allows 1 decimal place only' }] : []
        }
      });
    }
    case '#403': {
      const ref = params.ra_reference_id;
      const found = state.preDeclarations[ref];
      if (!found) return errorResponse(404, 'CDP_030', `找不到 ra_reference_id：${ref}`);
      found.payload = Object.assign({}, found.payload, body);
      found.status = scenario === 'cto_reject' ? 'REJECTED_FROM_CTO' : 'ACCEPTED_FROM_CTO';
      found.updatedAt = nowIso();
      return finish({
        status: 202,
        body: { ra_reference_id: ref, status: 'ACCEPTED', message: 'Update accepted for processing（async）', x_request_id: requestId },
        callback: {
          source_id: requestId, event: 'pre-declaration.updated', status: found.status, api,
          ra_reference_id: ref, cto_predeclaration_num: found.cto_predeclaration_num, ctoCode: found.ctoCode, cto_errors: []
        }
      });
    }
    case '#404': {
      const ref = params.ra_reference_id;
      const found = state.preDeclarations[ref];
      if (!found) return errorResponse(404, 'CDP_030', `找不到 ra_reference_id：${ref}`);
      delete state.preDeclarations[ref];
      return finish({
        status: 202,
        body: { ra_reference_id: ref, status: 'ACCEPTED', message: 'Delete accepted for processing（async）', x_request_id: requestId },
        callback: {
          source_id: requestId, event: 'pre-declaration.deleted', status: 'DELETED_FROM_CTO', api,
          ra_reference_id: ref, cto_predeclaration_num: found.cto_predeclaration_num, ctoCode: found.ctoCode, cto_errors: []
        }
      });
    }
    case '#405': {
      const seq = nextSeq(state);
      const ref = body.export_order_reference_num || `EO-${ctoCode}-${String(seq).padStart(6, '0')}`;
      state.exportOrders[ref] = {
        export_order_reference_num: ref,
        ctoCode,
        cargoType: body.cargoType || '',
        mawbNumber: body.mawbNumber || body.mawb || '',
        status: 'ACCEPTED',
        createdAt: nowIso(),
        payload: body
      };
      if (body.mawbNumber) state.mawbs[String(body.mawbNumber)] = { mawb: body.mawbNumber, createdAt: nowIso() };
      return finish({
        status: 200,
        body: {
          export_order_reference_num: ref,
          status: 'ACCEPTED',
          ctoCode,
          message: 'Export order created（mock）',
          receivedAt: nowIso()
        }
      });
    }
    case '#402': {
      const ref = params.ra_reference_id;
      if (ref) {
        const found = state.preDeclarations[ref];
        if (!found) return errorResponse(404, 'CDP_030', `找不到 ra_reference_id：${ref}`);
        return {
          status: 200,
          body: Object.assign({}, found.payload, {
            ra_reference_id: ref,
            cto_predeclaration_num: found.cto_predeclaration_num,
            status: found.status,
            updatedAt: found.updatedAt || found.createdAt
          })
        };
      }
      const ctoRef = params.cto_predeclaration_num;
      const byCto = Object.values(state.preDeclarations).find((p) => p.cto_predeclaration_num === ctoRef);
      if (!byCto) return errorResponse(404, 'CDP_030', `找不到 cto_predeclaration_num：${ctoRef || '(空白)'}`);
      return { status: 200, body: Object.assign({}, byCto.payload, { ra_reference_id: byCto.ra_reference_id, cto_predeclaration_num: byCto.cto_predeclaration_num, status: byCto.status }) };
    }
    case '#406': {
      const ref = params.export_order_reference_num;
      const found = state.exportOrders[ref];
      if (!found) return errorResponse(404, 'CDP_030', `找不到 export_order_reference_num：${ref}`);
      return { status: 200, body: Object.assign({}, found.payload, { export_order_reference_num: ref, status: found.status, updatedAt: found.createdAt }) };
    }
    case '#407': {
      const ref = params.export_order_reference_num;
      const found = state.exportOrders[ref];
      if (!found) return errorResponse(404, 'CDP_030', `找不到 export_order_reference_num：${ref}`);
      found.payload = Object.assign({}, found.payload, body);
      found.updatedAt = nowIso();
      return finish({ status: 200, body: { export_order_reference_num: ref, status: 'ACCEPTED', message: 'Export order updated（mock）' } });
    }
    case '#408': {
      const ref = params.export_order_reference_num;
      const found = state.exportOrders[ref];
      if (!found) return errorResponse(404, 'CDP_030', `找不到 export_order_reference_num：${ref}`);
      delete state.exportOrders[ref];
      return finish({ status: 200, body: { export_order_reference_num: ref, status: 'DELETED', message: 'Export order deleted（mock）' } });
    }
    case '#409': {
      const ref = params.export_order_reference_num;
      if (!state.exportOrders[ref]) return errorResponse(404, 'CDP_030', `找不到 export_order_reference_num：${ref}`);
      if (!body.imageBase64) return errorResponse(422, 'CDP_011', '缺少 imageBase64');
      if (!body.imageSignature) return errorResponse(422, 'CDP_050', '缺少 imageSignature（請先產生 SHA-256 + RSA 簽章）');
      const imageId = `IMG-${Date.now().toString(36).toUpperCase()}`;
      state.images[`${ref}:${imageId}`] = {
        imageId, exportOrderReferenceNum: ref, imageName: body.imageName || 'screening.jpg',
        imageHash: body.imageHash || '', createdAt: nowIso()
      };
      return finish({
        status: 200,
        body: {
          imageId,
          export_order_reference_num: ref,
          status: 'ACCEPTED',
          imageHash: body.imageHash || '',
          signatureVerified: true,
          message: 'Screening image uploaded（mock）'
        }
      });
    }
    case '#410': {
      const ref = params.ra_reference_id;
      if (ref && !state.preDeclarations[ref]) return errorResponse(404, 'CDP_030', `找不到 ra_reference_id：${ref}`);
      return {
        status: 200,
        body: {
          ra_reference_id: ref || '',
          cto_predeclaration_num: params.cto_predeclaration_num || (ref && state.preDeclarations[ref] ? state.preDeclarations[ref].cto_predeclaration_num : ''),
          truckArrivalTime: nowIso(),
          vehicleRegistration: body.vehicleRegistration || 'AB1234',
          dockCode: 'D01',
          status: 'ARRIVED',
          ctoCode
        }
      };
    }
    case '#411': {
      const ref = params.ra_reference_id;
      if (ref && !state.preDeclarations[ref]) return errorResponse(404, 'CDP_030', `找不到 ra_reference_id：${ref}`);
      const encodedPdf = await sampleRclPdfBase64(ref || params.cto_predeclaration_num || '', ctoCode);
      return {
        status: 200,
        body: {
          ra_reference_id: ref || '',
          cto_predeclaration_num: params.cto_predeclaration_num || '',
          rclNumber: `RCL-${Date.now().toString(36).toUpperCase()}`,
          issuedAt: nowIso(),
          encodedPdf,
          contentType: 'application/pdf',
          ctoCode
        }
      };
    }
    case '#412': {
      const ref = params.ra_reference_id;
      if (ref && !state.preDeclarations[ref]) return errorResponse(404, 'CDP_030', `找不到 ra_reference_id：${ref}`);
      return {
        status: 200,
        body: {
          ra_reference_id: ref || '',
          cto_predeclaration_num: params.cto_predeclaration_num || '',
          waybillNumber: params.waybill_num || body.waybillNumber || '',
          flightNumber: 'CX880',
          flightDate: nowIso().slice(0, 10),
          departureTime: nowIso(),
          status: 'DEPARTED',
          ctoCode
        }
      };
    }
    case '#415': {
      const seq = nextSeq(state);
      const ref = `RAL-${ctoCode}-${String(seq).padStart(6, '0')}`;
      const ctoRef = `CTOL${ctoCode}${String(seq).padStart(6, '0')}`;
      const rejected = scenario === 'cto_reject';
      const status = rejected ? 'REJECTED_FROM_CTO' : 'ACCEPTED_FROM_CTO';
      state.preDeclarations[ref] = {
        ra_reference_id: ref, cto_predeclaration_num: ctoRef, ctoCode,
        mawbNumber: body.mawbNumber || body.mawb || '', cargoType: body.cargoType || '',
        status, documentId: body.documentId || '', requestId, lite: true, createdAt: nowIso(), payload: body
      };
      return finish({
        status: 202,
        body: { ra_reference_id: ref, status: 'ACCEPTED', message: 'Lite pre-declaration accepted（async）', x_request_id: requestId },
        callback: {
          source_id: requestId, event: 'lite-pre-declaration.accepted', status, api,
          ra_reference_id: ref, cto_predeclaration_num: ctoRef, ctoCode,
          cto_errors: rejected ? [{ code: '108717', field: 'weight', message: 'Weight allows 1 decimal place only' }] : []
        }
      });
    }
    case '#416': {
      const mawb = params.mawb_num;
      if (!mawb) return errorResponse(400, 'CDP_011', '缺少 mawb_num');
      delete state.mawbs[mawb];
      return finish({ status: 200, body: { mawb_num: mawb, status: 'DELETED', message: 'MAWB deleted（mock）' } });
    }
    default:
      return errorResponse(400, 'CDP_010', `Local Mock 尚未支援 ${api}`);
  }
}

module.exports = { handleMock, scenarioOf, sampleRclPdfBase64 };
